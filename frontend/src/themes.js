export const AVAILABLE_MOOD_KEYS = [
  'funny',
  'thrilling',
  'romantic',
  'thoughtful',
  'dark',
  'feel-good',
];

export function getTheme(moodId) {
  if (!moodId) return MOOD_THEMES.default;
  const key = String(moodId).toLowerCase().trim();
  return MOOD_THEMES[key] || MOOD_THEMES.default;
}

export function getRandomMood() {
  const idx = Math.floor(Math.random() * AVAILABLE_MOOD_KEYS.length);
  return AVAILABLE_MOOD_KEYS[idx];
}
